def template_root() -> Path:
    return Path(__file__).resolve().parents[1]


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def project_keys(text: str) -> dict[str, str]:
    found: dict[str, str] = {}
    for line in text.splitlines():
        match = KEY_RE.match(line)
        if match:
            found[match.group(1).strip()] = match.group(2).strip().replace("`", "")
    return found


def token(value: str) -> str:
    value = value.strip()
    return value.split()[0] if value else ""


def sections(text: str) -> dict[str, str]:
    found: dict[str, str] = {}
    parts = re.split(r"(?=^## )", text, flags=re.M)
    for part in parts:
        match = SECTION_RE.match(part)
        if not match:
            continue
        body = part[match.end() :].strip()
        found[match.group(1).strip()] = body
    return found


def tool_text(project: Path) -> tuple[str, bool]:
    config = project / ".agent-tools" / "config.md"
    if config.is_file():
        return read_text(config), False
    project_md = project / "PROJECT.md"
    text = read_text(project_md) if project_md.is_file() else ""
    legacy = any(key in project_keys(text) for key in ("Stack", "Docs impact", "Agent layer", "Merge reviewer"))
    return text, legacy


def load_settings(project: Path) -> tuple[dict[str, str], dict[str, str], bool]:
    raw, legacy = tool_text(project)
    keys = project_keys(raw)
    guidance = read_text(project / "PROJECT.md") if (project / "PROJECT.md").is_file() else ""
    return keys, sections(guidance), legacy


def local_override_path(project: Path) -> Path:
    try:
        out = subprocess.run(
            ["git", "-C", str(project), "rev-parse", "--path-format=absolute", "--git-path", "agent-tools.local"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        if out:
            return Path(out)
    except (OSError, subprocess.CalledProcessError):
        pass
    return project / ".git" / "agent-tools.local"


def resolve_host(project: Path, keys: dict[str, str], flag: str = "") -> str:
    """Flag > <git-dir>/agent-tools.local > tool config > both."""
    value = flag.strip().lower()
    if not value:
        local = local_override_path(project)
        if local.is_file():
            value = token(project_keys(read_text(local)).get("Agent host", "")).lower()
    if not value:
        value = token(keys.get("Agent host", "")).lower()
    if value not in HOSTS:
        if value:
            print(f"cursor-template: unknown Agent host '{value}', using both", file=sys.stderr)
        return "both"
    return value


def host_has(host: str, tool: str) -> bool:
    return host in ("both", tool)


def code_roots(text: str) -> list[str]:
    match = re.search(r"^## Code roots\n(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not match:
        return []
    fence = FENCE_RE.search(match.group(1))
    blob = fence.group(1) if fence else match.group(1)
    roots: list[str] = []
    for line in blob.splitlines():
        line = line.split("#", 1)[0].strip().strip("`")
        if not line or "REPLACE_ME" in line or "/" not in line:
            continue
        roots.append(line if line.endswith("/") else line + "/")
    return roots


def notes_mode(keys: dict[str, str]) -> str:
    explicit = token(keys.get("Notes check", "")).lower()
    if explicit in {"ci", "local", "off"}:
        return explicit
    docs = token(keys.get("Docs impact", "off")).lower() or "off"
    if docs == "ci":
        return "ci"
    if docs == "local":
        return "local"
    return "off"


def append_section(body: str, title: str, extra: str) -> str:
    extra = extra.strip()
    if not extra or extra == "(none)":
        return body
    return body.rstrip() + f"\n\n## {title}\n\n{extra}\n"


def generated_header(current: str) -> bool:
    first = current.lstrip().splitlines()[0].strip() if current.strip() else ""
    known = {TEAM_HEADER.strip(), LOCAL_HEADER.strip(), *(item.strip() for item in LEGACY_HEADERS)}
    return first in known


def is_generated(path: Path) -> bool:
    """True for a file this generator wrote. The marker may sit below a YAML frontmatter."""
    if not path.is_file() or path.is_symlink():
        return False
    head = path.read_text(encoding="utf-8").splitlines()[:8]
    return any(line.strip() == LOCAL_HEADER.strip() for line in head)


def retire_own_symlink(path: Path, root: Path) -> bool:
    """Remove a symlink an older install made into this checkout. True when the path is free to write."""
    if not path.is_symlink():
        return True
    try:
        Path(os.path.realpath(path)).relative_to(root.resolve())
    except (OSError, ValueError):
        return False
    path.unlink()
    return True


def claude_contract(agents: str) -> str:
    """AGENTS.md text for Claude Code: no section whose heading says (Cursor only), pointer reworded."""
    parts = re.split(r"(?=^## )", agents, flags=re.M)
    kept = []
    for part in parts:
        match = SECTION_RE.match(part)
        if match and CURSOR_ONLY in match.group(1):
            continue
        kept.append(part.rstrip() + "\n\n")
    text = "".join(kept).rstrip() + "\n"
    return text.replace(CODING_POINTER, CLAUDE_CODING_POINTER)


def render_team(root: Path, project: Path, reviewer_enabled: bool) -> tuple[str, str]:
    del reviewer_enabled
    keys, bodies, _legacy = load_settings(project)
    docs = token(keys.get("Docs impact", "off")) or "off"
    agents = read_text(root / "AGENTS.md").strip()
    choice = token(keys.get("Opus parent", "")).lower()
    if choice == "may-read":
        agents = agents.replace(NEUTRAL_OPUS, MAY_READ_OPUS)
    elif choice == "orchestrate-only":
        agents = agents.replace(NEUTRAL_OPUS, ORCHESTRATE_ONLY_OPUS)
    agents += "\n\n" + LOCAL_SENTENCE + "\n"
    if docs == "ci":
        agents += (
            "\n## Docs check\n\n"
            "A behaviour change in mapped code needs a docs update in the same change. "
            "CI runs `python3 docs/ci/docs-impact.py`.\n"
        )
    if notes_mode(keys) == "ci":
        agents += (
            "\n## Notes check\n\n"
            "CI runs `python3 docs/ci/notes-append-only.py --base <ref>` "
            "so an edited or deleted `docs/notes/` file fails the docs job.\n"
        )
    for title in ("Environment", "Quality bar", "Agent rules"):
        agents = append_section(agents, title, bodies.get(title, ""))
    claude = read_text(root / "CLAUDE.md").strip() + "\n"
    if choice == "may-read":
        claude = claude.replace(CLAUDE_NEUTRAL_OPUS, CLAUDE_MAY_READ_OPUS)
    elif choice == "orchestrate-only":
        claude = claude.replace(CLAUDE_NEUTRAL_OPUS, CLAUDE_ORCHESTRATE_ONLY_OPUS)
    # Environment, Quality bar, and Agent rules ride along in the inlined contract.
    contract = claude_contract(agents)
    if CONTRACT_MARKER in claude:
        claude = claude.replace(CONTRACT_MARKER, contract.strip())
    else:
        claude = claude.rstrip() + "\n\n" + contract
    if token(keys.get("Stack", "")) == "magento2":
        claude = append_section(claude, "Tests", PHPUNIT_EVERYDAY)
    claude = append_section(claude, "Overview", bodies.get("Overview", ""))
    claude = append_section(claude, "Claude", bodies.get("Claude", ""))
    return TEAM_HEADER + "\n" + agents, TEAM_HEADER + "\n" + claude


def skill_rows(project: Path, reviewer_enabled: bool, base: str = ".cursor/skills") -> list[tuple[str, str]]:
    rows = [
        ("Behaviour, config, or contract change", f"{base}/update-feature-docs/SKILL.md"),
        ("Pasted tracker issue", f"{base}/reproduce-jira/SKILL.md"),
    ]
    if (project / base / "write-phpunit").exists():
        rows.append(("Unit tests for a Magento module", f"{base}/write-phpunit/SKILL.md"))
    if reviewer_enabled:
        extra = [
            ("Apply a fix list", f"{base}/apply-review-fixes/SKILL.md"),
            ("Skip a fix list", f"{base}/skip-review-fixes/SKILL.md"),
        ]
        if base == ".cursor/skills":
            extra.insert(0, ("After a coherent diff", f"{base}/review-change/SKILL.md"))
        for label, path in extra:
            if (project / path).parent.exists() or (project / path).exists():
                rows.append((label, path))
    return rows


def notes_text(keys: dict[str, str]) -> str:
    mode = notes_mode(keys)
    if mode == "ci":
        return (
            "The committed notes check is `python3 docs/ci/notes-append-only.py`. "
            "The pre-commit hook runs that copy with `--staged` when it is present."
        )
    if mode == "local":
        return (
            "After appending to `docs/notes/`, run `python3 docs/scripts/notes-append-only.py` until it prints `ok`. "
            "The pre-commit hook runs it with `--staged` and blocks the commit when an old entry changed."
        )
    return "Notes check is off on this laptop."


def docs_impact_text(keys: dict[str, str]) -> str:
    docs = token(keys.get("Docs impact", "off")) or "off"
    layer = token(keys.get("Agent layer", "committed")) or "committed"
    if docs == "local" or (docs == "ci" and layer == "local"):
        return (
            "Hidden docs are not staged. The pre-commit check is advisory: it prints findings and does not block. "
            "Ignored files under `docs/` edited since HEAD count as the docs update."
        )
    if docs == "ci":
        return "This repository commits docs. The pre-commit check runs `python3 docs/ci/docs-impact.py --staged` and blocks when mapped code has no docs update."
    return "Docs impact is off on this laptop. Do not run a docs-impact command."


def render_cursor_local(project: Path, reviewer_enabled: bool, keys: dict[str, str]) -> str:
    lines = [
        "---",
        "description: Laptop-only tool rules. Teammates without these tools do not have this file.",
        "alwaysApply: true",
        "---",
        "",
        "# Local agent tools",
        "",
        "These rules are present only on a laptop where the tool checkout is linked.",
        "",
        "## Skills",
        "",
        "| Task | File |",
        "| --- | --- |",
    ]
    for label, path in skill_rows(project, reviewer_enabled):
        lines.append(f"| {label} | `{path}` |")
    lines.extend(["", "## Notes", "", notes_text(keys), "", "## Docs impact", "", docs_impact_text(keys)])
    if reviewer_enabled:
        model = keys.get("Review model", "").strip() or "the configured model"
        lines.extend(
            [
                "",
                "## Review",
                "",
                "When this laptop has the reviewer linked, a later commit starts it in the background. It does not block git.",
                "Do not judge your own diff in the chat that wrote the code.",
                f"The model is {model}.",
                "Skip a run with `REVIEW_CHANGE=0`, `REVIEW_CHANGE_SKIP=1`, or `[skip review]` in the commit subject.",
                "A configured pre-review command may run first. Its failure does not fail the commit.",
            ]
        )
    return LOCAL_HEADER + "\n" + "\n".join(lines).rstrip() + "\n"


def render_claude_local(project: Path, reviewer_enabled: bool, keys: dict[str, str]) -> str:
    # Skills are listed to Claude by their own descriptions, so no skills table here.
    lines = [
        LOCAL_HEADER.rstrip("\n"),
        "",
        "# CLAUDE.local.md",
        "",
        "Laptop-only, rewritten on every install.",
        "",
        "## Notes",
        "",
        notes_text(keys),
        "",
        "## Docs impact",
        "",
        docs_impact_text(keys),
    ]
    if reviewer_enabled:
        lines.extend(
            [
                "",
                "## Review",
                "",
                "A later commit starts merge-reviewer in the background; it does not block git. "
                "The report is `var/review-change.html` and `.md`; read it only when the user asks about the review.",
                "Do not review your own diff in this chat or start a review from it. "
                "Apply or skip the fix list with the `apply-review-fixes` or `skip-review-fixes` skill.",
                "Skip a run with `REVIEW_CHANGE=0`, `REVIEW_CHANGE_SKIP=1`, or `[skip review]` in the commit subject. "
                "Setup: `docs/developer/review-change.md`.",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def render_claude_phpunit(root: Path) -> str:
    """.claude/rules/phpunit.md from the Cursor rule: paths-scoped, no everyday-work section."""
    text = read_text(root / "adapters" / "magento2" / "rules" / "phpunit.mdc")
    if text.startswith("---"):
        end = text.find("\n---", 3)
        if end != -1:
            text = text[end + 4 :]
    text = text.replace(".cursor/skills/", ".claude/skills/")
    kept = []
    for part in re.split(r"(?=^## )", text.strip(), flags=re.M):
        match = SECTION_RE.match(part)
        if match and match.group(1).strip() == "Everyday work":
            continue
        kept.append(part.rstrip() + "\n\n")
    front = "---\npaths:\n" + "".join(f'  - "{item}"\n' for item in PHPUNIT_PATHS) + "---\n"
    return front + LOCAL_HEADER + "\n" + "".join(kept).rstrip() + "\n"


def render_local(project: Path, reviewer_enabled: bool) -> tuple[str, str]:
    keys, _bodies, _legacy = load_settings(project)
    return render_cursor_local(project, reviewer_enabled, keys), render_claude_local(project, reviewer_enabled, keys)


def classify(path: Path, expected: str, header: str) -> str:
    del header
    if not path.is_file():
        return "missing"
    current = path.read_text(encoding="utf-8")
    if not generated_header(current):
        return "hand-edited"
    if current != expected:
        return "stale"
    return "fresh"


def write_team(path: Path, expected: str, force: bool) -> str:
    state = classify(path, expected, TEAM_HEADER)
    if state == "hand-edited" and not force:
        return "hand-edited"
    if state == "fresh":
        return "fresh"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8")
    return "wrote"


def clean_rel(value: str) -> str:
    value = value.strip().strip("`")
    if value.startswith("./"):
        value = value[2:]
    return value.rstrip("/")


def kept_paths(keys: dict[str, str]) -> set[str]:
    found: set[str] = set()
    for part in keys.get("Keep local", "").split(","):
        item = clean_rel(part)
        if item:
            found.add(item)
    return found


def filter_matches(filt: str, stack: str, docs: str) -> bool:
    """Comma-joined parts must all match. Host parts match every host: team files must not name any link."""
    if not filt:
        return True
    for part in filt.split(","):
        if part in ("host:cursor", "host:claude") or part == stack:
            continue
        if part == "docs-impact:local" and docs == "local":
            continue
        return False
    return True


def link_only_paths(root: Path, keys: dict[str, str]) -> list[str]:
    stack = token(keys.get("Stack", "generic")) or "generic"
    docs = token(keys.get("Docs impact", "off")) or "off"
    layer = token(keys.get("Agent layer", "committed")) or "committed"
    kept = kept_paths(keys)
    paths: list[str] = []
    for raw in (root / "install" / "links.txt").read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        vendor = False
        filt = ""
        rest = line
        if line.startswith("["):
            filt, rest = line[1:].split("]", 1)
            rest = rest.strip()
            if filt == "vendor:committed":
                vendor = True
                filt = ""
        parts = rest.split()
        if len(parts) != 2 or not filter_matches(filt, stack, docs):
            continue
        dest = clean_rel(parts[1])
        if vendor and layer == "committed":
            continue
        if dest in kept:
            continue
        paths.append(dest)
        if dest.startswith(".cursor/skills/"):
            paths.append(".claude/skills/" + dest.removeprefix(".cursor/skills/"))
    return sorted(set(paths), key=len, reverse=True)


def scan_text(rel: str, text: str, paths: list[str]) -> None:
    in_entry = False
    notes_file = rel.startswith("docs/notes/") and rel.endswith(".md")
    for number, line in enumerate(text.splitlines(), start=1):
        if notes_file and line.startswith("### "):
            in_entry = True
        for path in paths:
            if path and path in line:
                kind = "team-ref-in-history" if notes_file and in_entry else "team-ref-to-local"
                print(f"{kind} {rel}:{number} {path}")
                break


def iter_committed_docs(project: Path):
    docs = project / "docs"
    if not docs.is_dir() or docs.is_symlink():
        return
    for dirpath, dirnames, filenames in os.walk(docs, followlinks=False):
        current = Path(dirpath)
        dirnames[:] = [name for name in dirnames if not (current / name).is_symlink()]
        for name in filenames:
            path = current / name
            if name.endswith(".md") and path.is_file() and not path.is_symlink():
                yield path


def scan_team_refs(root: Path, project: Path) -> None:
    keys, _bodies, _legacy = load_settings(project)
    layer = token(keys.get("Agent layer", "committed")) or "committed"
    if layer == "local":
        print("team-refs: skipped (agent layer local)")
        return
    paths = link_only_paths(root, keys)
    if not paths:
        return
    targets: list[Path] = []
    for name in ("AGENTS.md", "CLAUDE.md", ".cursorrules", "PROJECT.md", "CODING_PRINCIPLES.md"):
        path = project / name
        if path.is_file() and not path.is_symlink():
            targets.append(path)
    if layer == "committed":
        targets.extend(iter_committed_docs(project))
    for path in targets:
        scan_text(path.relative_to(project).as_posix(), path.read_text(encoding="utf-8", errors="replace"), paths)


def hand_message(path: Path, project: Path) -> str:
    section = "## Agent rules" if path.name == "AGENTS.md" else "## Claude"
    return (
        f"install: {path.name} has no generator header. "
        f"Move its project text into PROJECT.md {section}, then rerun: "
        f"install/install.sh {project} --adopt"
    )


def seed_config(root: Path, project: Path, mode: str) -> int:
    keys, _bodies, _legacy = load_settings(project)
    guidance = read_text(project / "PROJECT.md") if (project / "PROJECT.md").is_file() else ""
    stack = token(keys.get("Stack", "generic")) or "generic"
    if mode == "ci":
        dest = project / "docs" / "ci" / "docs-impact.config.json"
    elif mode == "local":
        dest = project / "docs" / "scripts" / "docs-impact.config.json"
    else:
        print(f"docs-impact config: unknown mode {mode}", file=sys.stderr)
        return 1
    if dest.is_file():
        print(f"docs-impact config: present {dest.relative_to(project)}")
        return 0
    example = root / "tools" / "docs-impact.config.example.json"
    data = json.loads(example.read_text(encoding="utf-8"))
    roots = code_roots(guidance)
    if roots:
        data["custom_code_prefixes"] = roots
    if stack == "magento2":
        data["module_folder_template"] = "app/code/{vendor}/{name}/"
        data["core_module_prefixes"] = ["Magento_"]
        themes = [item for item in roots if "/design/" in f"/{item}"]
        if themes:
            data["theme_or_app_roots"] = themes
    elif stack == "shopify":
        data["module_folder_template"] = ""
        data["core_module_prefixes"] = []
        themes = [
            item
            for item in roots
            if item.rstrip("/").split("/")[-1] in {"sections", "blocks", "snippets"}
        ]
        if themes:
            data["theme_or_app_roots"] = themes
    else:
        data["module_folder_template"] = ""
        data["core_module_prefixes"] = []
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"docs-impact config: wrote {dest.relative_to(project)}")
    return 0


def opt_out_path(project: Path) -> Path:
    git_dir = project / ".git"
    return git_dir / "agent-tools.local"


def migrate_config(project: Path) -> int:
    source = project / "PROJECT.md"
    if not source.is_file():
        print("migrate-config: missing PROJECT.md", file=sys.stderr)
        return 1
    text = source.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)
    kept: list[str] = []
    moved: list[str] = []
    repro: list[str] = []
    in_repro = False
    reviewer = ""
    has_quality = any(line.startswith("## Quality bar") for line in lines)
    moved_names: list[str] = []
    for line in lines:
        if line.startswith("## "):
            in_repro = False
            title = line[3:].strip()
            if title == "Reproduce ticket":
                in_repro = True
                repro.append(line if line.endswith("\n") else line + "\n")
                moved_names.append("## Reproduce ticket")
                continue
            if title == "Review rules" and not has_quality:
                kept.append("## Quality bar\n" if line.endswith("\n") else "## Quality bar\n")
                moved_names.append("## Review rules → ## Quality bar")
                continue
        if in_repro:
            repro.append(line if line.endswith("\n") else line + "\n")
            continue
        match = KEY_RE.match(line.rstrip("\n"))
        if match and match.group(1).strip() in MOVE_KEYS:
            key = match.group(1).strip()
            if key == "Merge reviewer":
                reviewer = token(match.group(2))
                moved_names.append("Merge reviewer (dropped from git)")
                continue
            moved.append(line if line.endswith("\n") else line + "\n")
            moved_names.append(key)
            continue
        kept.append(line if line.endswith("\n") else line + "\n")
    dest = project / ".agent-tools" / "config.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    existing = dest.read_text(encoding="utf-8") if dest.is_file() else ""
    existing_keys = set(project_keys(existing))
    fresh = [line for line in moved if KEY_RE.match(line.rstrip("\n")) and KEY_RE.match(line.rstrip("\n")).group(1).strip() not in existing_keys]
    body = existing
    if fresh or repro:
        if body and not body.endswith("\n"):
            body += "\n"
        if not body:
            body = "# Tool config\n\n"
        body += "".join(fresh)
        if repro:
            if not body.endswith("\n"):
                body += "\n"
            body += "\n" + "".join(repro)
        dest.write_text(body, encoding="utf-8")
    source.write_text("".join(kept), encoding="utf-8")
    if reviewer == "off":
        opt = opt_out_path(project)
        opt.parent.mkdir(parents=True, exist_ok=True)
        current = opt.read_text(encoding="utf-8") if opt.is_file() else ""
        if "- **Merge reviewer:**" not in current:
            if current and not current.endswith("\n"):
                current += "\n"
            opt.write_text(current + "- **Merge reviewer:** off\n", encoding="utf-8")
        print("migrate-config: Merge reviewer was off; wrote .git/agent-tools.local")
    print("migrate-config: moved " + (", ".join(moved_names) if moved_names else "(nothing)"))
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("project", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--reviewer-enabled", action="store_true")
    parser.add_argument("--host", choices=HOSTS)
    parser.add_argument("--seed-config", choices=("ci", "local"))
    parser.add_argument("--migrate-config", action="store_true")
    args = parser.parse_args()

    project = args.project.resolve()
    root = template_root()
    if args.migrate_config:
        return migrate_config(project)
    if not (project / "PROJECT.md").is_file():
        print(f"generate-agent-docs: missing {project / 'PROJECT.md'}", file=sys.stderr)
        return 1
    if args.seed_config:
        return seed_config(root, project, args.seed_config)

    keys, _bodies, legacy = load_settings(project)
    host = resolve_host(project, keys, args.host or "")
    if legacy:
        print("cursor-template: switches still in PROJECT.md — run install.sh --migrate-config", file=sys.stderr)

    agents_text, claude_text = render_team(root, project, args.reviewer_enabled)
    local_rule, local_claude = render_local(project, args.reviewer_enabled)
    team = {
        project / "AGENTS.md": agents_text,
        project / "CLAUDE.md": claude_text,
    }
    local = {}
    stale_local = []
    for tool, path, text in (
        ("cursor", project / ".cursor/rules/agent-tools.mdc", local_rule),
        ("claude", project / "CLAUDE.local.md", local_claude),
    ):
        if host_has(host, tool):
            local[path] = text
        else:
            stale_local.append(path)
    phpunit_path = project / ".claude/rules/phpunit.md"
    if host_has(host, "claude") and token(keys.get("Stack", "")) == "magento2":
        local[phpunit_path] = render_claude_phpunit(root)
    else:
        stale_local.append(phpunit_path)
    failed = False
    hand_edited = False
    for path, expected in team.items():
        if args.check:
            state = classify(path, expected, TEAM_HEADER)
            if state == "hand-edited":
                print(hand_message(path, project), file=sys.stderr)
                hand_edited = True
                continue
            print(f"{path.name}: {state}")
            if state != "fresh":
                failed = True
            continue
        state = write_team(path, expected, args.force)
        if state == "hand-edited":
            print(hand_message(path, project), file=sys.stderr)
            hand_edited = True
            continue
        print(f"{path.name}: {state}")
    for path, expected in local.items():
        if path == phpunit_path and (path.is_symlink() or (path.exists() and not is_generated(path))):
            owned_link = path.is_symlink() and Path(os.path.realpath(path)).is_relative_to(root.resolve())
            if not owned_link:
                print(f"{path.name}: kept (project file, not generated)")
                continue
            if args.check:
                print(f"{path.name}: stale (old symlink)")
                failed = True
                continue
            retire_own_symlink(path, root)
        if args.check:
            state = "missing" if not path.is_file() else ("fresh" if path.read_text(encoding="utf-8") == expected else "stale")
            print(f"{path.name}: {state}")
            if state != "fresh":
                failed = True
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.is_file() and path.read_text(encoding="utf-8") == expected:
            print(f"{path.name}: fresh")
            continue
        path.write_text(expected, encoding="utf-8")
        print(f"{path.name}: wrote")
    for path in stale_local:
        generated = is_generated(path) if path == phpunit_path else (
            path.is_file() and generated_header(path.read_text(encoding="utf-8"))
        )
        if not generated:
            continue
        if args.check:
            print(f"{path.name}: stale (agent host {host})")
            failed = True
            continue
        path.unlink()
        print(f"{path.name}: removed (agent host {host})")
    if args.check:
        scan_team_refs(root, project)
    if hand_edited:
        return 2
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
