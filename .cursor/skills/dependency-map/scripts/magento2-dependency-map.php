function rfiles(string $dir, string $re): array
{
    if (!is_dir($dir)) return [];
    $out = [];
    $it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($dir, FilesystemIterator::SKIP_DOTS | FilesystemIterator::FOLLOW_SYMLINKS));
    foreach ($it as $f) {
        $p = $f->getPathname();
        if (preg_match($re, $p) && !preg_match('#/(Test|tests|node_modules)/#', $p)) $out[] = $p;
    }
    sort($out);
    return $out;
}
function attr(string $tag, string $name): string
{
    return preg_match('/\b' . preg_quote($name, '/') . '\s*=\s*"([^"]*)"/', $tag, $m) ? trim($m[1]) : '';
}
function xmlText(string $file): string
{
    return preg_replace('/<!--.*?-->/s', '', (string)@file_get_contents($file));
}

// ---- vendor index: packages, namespaces, module and theme directories, view files (relative to the root)
function buildVendorIndex(string $root): array
{
    $installed = json_decode(file_get_contents("$root/vendor/composer/installed.json"), true);
    $index = ['packages' => [], 'modules' => [], 'themes' => [], 'files' => []];
    foreach ($installed['packages'] ?? $installed as $p) {
        $name = $p['name'];
        $ns = [];
        foreach (['psr-4', 'psr-0'] as $k) {
            foreach (array_keys($p['autoload'][$k] ?? []) as $n) if ($n !== '') $ns[] = rtrim($n, '\\') . '\\';
        }
        $index['packages'][$name] = ['version' => $p['version'] ?? '?', 'require' => $p['require'] ?? [], 'ns' => $ns];
        $dir = "$root/vendor/$name";
        foreach (array_merge(glob("$dir/registration.php") ?: [], glob("$dir/*/registration.php") ?: [], glob("$dir/*/*/registration.php") ?: []) as $reg) {
            $src = (string)@file_get_contents($reg);
            $relDir = substr(dirname($reg), strlen($root) + 1);
            if (preg_match("/ComponentRegistrar::MODULE,\s*'([^']+)'/", $src, $m)) {
                $index['modules'][$m[1]] = [$name, $relDir];
                foreach (['view/frontend', 'view/base'] as $v) {
                    foreach (rfiles(dirname($reg) . "/$v", '/\.(phtml|html|js|css)$/') as $f) $index['files'][substr($f, strlen($root) + 1)] = 1;
                }
            }
            if (preg_match("/ComponentRegistrar::THEME,\s*'([^']+)'/", $src, $m)) {
                $index['themes'][$m[1]] = $relDir;
                foreach (rfiles(dirname($reg), '/\.(phtml|html|js|css|xml)$/') as $f) $index['files'][substr($f, strlen($root) + 1)] = 1;
                $index['themexml'][$m[1]] = (string)@file_get_contents(dirname($reg) . '/theme.xml');
            }
        }
    }
    return $index;
}
