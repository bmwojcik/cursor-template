 * Dependency risk map for a Magento 2 project: which custom code extends or calls which third-party package.
 * Reads files only. No Magento bootstrap, no vendor/autoload.php, no XML extension needed (PHP 8.0+).
 *
 * Project files (app/code, app/design, patches, composer.json, composer.lock, docs) are read from the git
 * checkout. vendor/ is best read from the running container, which holds what the shop actually runs; a local
 * vendor/ can be stale. Two steps, both piping this script through stdin:
 *
 *   1. in the container:  <container php> -- <root-in-container> --emit-vendor-index < magento2-dependency-map.php > var/dependency-map.vendor.json
 *   2. on the host:       php -- . --vendor-index=var/dependency-map.vendor.json --source=container [options] < magento2-dependency-map.php > docs/architecture/dependency-map.md
 *
 * Fallback without a container: step 2 alone with --source=local-vendor (reads ./vendor).
 *
 * --vendor-index  vendor index from step 1 (otherwise ./vendor is scanned)
 * --vendored  third-party modules copied into app/code (e.g. Amasty,Dialcom/Przelewy): mapped as packages
 *             named "app/code/<dir>" and left out of the custom-code scan
 * --roots    vendor directories under app/code that hold custom code (default: all except Magento)
 * --exclude  package-name prefixes to leave out (default: platform and generic libraries)
 * --index    INDEX file relative to the root, for the Features column (skipped when missing)
 * --source   recorded in the header so readers know whether the container or a local vendor/ was read
 */

