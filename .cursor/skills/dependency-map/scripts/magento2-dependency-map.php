    $c = $direct[$pkg] ?? (str_starts_with($pkg, 'app/code/') ? 'vendored copy' : null);
    $constraintKind = $c === 'vendored copy' ? 'range' : ($c === null ? 'transitive' : (preg_match('/^v?\d+(\.\d+)*(-p\d+)?$/', $c) ? 'exact' : ($c === '*' ? 'wildcard' : 'range')));
    $loose = $constraintKind !== 'exact';
    if (isset($kinds['preference']) || isset($kinds['extends']) || isset($kinds['patch']) || (isset($kinds['plugin']) && $loose)) {
        $risk = 'high';
    } elseif (array_intersect_key($kinds, ['plugin' => 1, 'theme-override' => 1, 'layout' => 1, 'constructor' => 1])) {
        $risk = 'medium';
    } else {
        $risk = 'low';
    }
    $score = 0;
    foreach ($kinds as $k => $n) $score += ($weights[$k] ?? 1) * $n;
    $wrappers = [];
    foreach ($requires as $other => $req) {
        if ($other !== $pkg && isset($req[$pkg]) && $isTracked($other)) $wrappers[$other] = $req[$pkg];
    }
    ksort($kinds);
    $rows[$pkg] = [
        'package' => $pkg,
        'version' => $version[$pkg] ?? '?',
        'constraint' => $c ?? 'transitive',
        'risk' => $risk,
        'score' => $score,
        'kinds' => $kinds,
        'consumers' => array_keys($consumers),
        'features' => $featuresFor($pkg, array_keys($consumers)),
        'wrappers' => $wrappers,
        'refs' => array_values($items),
    ];
}
$order = ['high' => 0, 'medium' => 1, 'low' => 2];
uasort($rows, fn ($a, $b) => [$order[$a['risk']], -$a['score'], $a['package']] <=> [$order[$b['risk']], -$b['score'], $b['package']]);

// ---- render
$md = fn (string $s) => str_replace('|', '\|', $s);
$out = [];
$out[] = '<!-- generated by cursor-template dependency-map; do not edit by hand -->';
$out[] = '# ' . $L['title'];
$out[] = '';
$out[] = $L['intro'];
$out[] = '';
$out[] = "- {$L['source']}: `{$opt['source']}`; roots: `" . implode('`, `', $roots) . '`';
$out[] = "- {$L['lock']}: `" . ($lock['content-hash'] ?? '?') . '`';
$out[] = '';
$out[] = '## ' . $L['summary'];
$out[] = '';
$out[] = $L['legend'];
$out[] = '';
$out[] = '| ' . implode(' | ', $L['cols']) . ' |';
$out[] = '| ' . implode(' | ', array_fill(0, count($L['cols']), '---')) . ' |';
foreach ($rows as $r) {
    $kinds = implode(', ', array_map(fn ($k, $n) => "$k $n", array_keys($r['kinds']), $r['kinds']));
    $out[] = sprintf(
        '| `%s` | %s | `%s` | **%s** | %s | %s | %s |',
        $r['package'],
        $md($r['version']),
        $md($r['constraint']),
        $r['risk'],
        $md(implode(', ', array_map(fn ($c) => "`$c`", $r['consumers']))),
        $kinds,
        $r['features'] ? implode(', ', array_map(fn ($s) => "[$s](../features/INDEX.md)", $r['features'])) : '—'
    );
}
$out[] = '';
$out[] = '## ' . $L['health'];
$out[] = '';
$out[] = '### ' . $L['orphans'];
$out[] = '';
$out[] = $L['orphansNote'];
$out[] = '';
if ($orphans) {
    foreach ($orphans as [$f, $pkg]) $out[] = "- `$f` ($pkg)";
} else {
    $out[] = '- ' . $L['none'];
}
$out[] = '';
$out[] = '### ' . $L['orphanPatches'];
$out[] = '';
if ($orphanPatches) {
    foreach ($orphanPatches as [$f, $pkg]) $out[] = "- `$f` (`$pkg`)";
} else {
    $out[] = '- ' . $L['none'];
}
$out[] = '';
$out[] = '### ' . $L['wrappers'];
$out[] = '';
$any = false;
foreach ($rows as $r) {
    if ($r['risk'] === 'low' || !$r['wrappers']) continue;
    $list = [];
    foreach ($r['wrappers'] as $w => $c) {
        if (preg_match('/^v?\d+(\.\d+)*(-p\d+)?$/', $c)) continue; // an exact pin cannot drift
        $list[] = "`$w` `" . $md($c) . '`';
    }
    if (!$list) continue;
    $more = count($list) > 6 ? ' … (+' . (count($list) - 6) . ')' : '';
    $out[] = "- `{$r['package']}` {$r['version']}: " . implode(', ', array_slice($list, 0, 6)) . $more;
    $any = true;
}
if (!$any) $out[] = '- ' . $L['none'];
$out[] = '';
$out[] = '## ' . $L['details'];
foreach ($rows as $r) {
    $out[] = '';
    $out[] = "### `{$r['package']}` {$r['version']} ({$r['risk']})";
    $out[] = '';
    usort($r['refs'], fn ($a, $b) => [$a[0], $a[1], $a[2]] <=> [$b[0], $b[1], $b[2]]);
    foreach ($r['refs'] as [$kind, $consumer, $symbol, $file]) {
        $out[] = "- $kind · `$consumer` · `" . $md($symbol) . "` · `$file`";
    }
}
$data = [];
foreach ($rows as $r) {
    $data[$r['package']] = [
        'version' => $r['version'],
        'constraint' => $r['constraint'],
        'risk' => $r['risk'],
        'consumers' => $r['consumers'],
        'features' => $r['features'],
        'refs' => array_map(fn ($x) => ['kind' => $x[0], 'consumer' => $x[1], 'symbol' => $x[2], 'file' => $x[3]], $r['refs']),
    ];
}
$out[] = '';
$out[] = '<!-- dependency-map:data';
$out[] = str_replace('--', '--', json_encode(['stack' => 'magento2', 'lock' => 'composer.lock', 'packages' => $data], JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE));
$out[] = '-->';
echo implode("\n", $out), "\n";
fwrite($err, sprintf("dependency-map: %d packages, %d high, %d orphan overrides, source=%s\n", count($rows), count(array_filter($rows, fn ($r) => $r['risk'] === 'high')), count($orphans), $opt['source']));
