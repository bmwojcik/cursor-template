                foreach ([$h[1] ?? '', $h[2] ?? ''] as $list) {
                    foreach (array_filter(array_map('trim', explode(',', $list))) as $t) {
                        $fq = resolveName($t, $uses, $ns);
                        $add($pkgOf($fq), 'extends', $consumer, $fq, $rel($file));
                        $seen[$fq] = true;
                    }
                }
            }
            if (preg_match('/function\s+__construct\s*\((.*?)\)\s*[{:]/s', $src, $cm)) {
                preg_match_all('/(?:^|,|\()\s*(?:#\[[^\]]*\]\s*)?(?:(?:public|private|protected|readonly)\s+)*\??([\\\\\w]+)\s+&?\s*(?:\.\.\.)?\$\w+/', $cm[1], $pm);
                foreach ($pm[1] as $t) {
                    if (preg_match('/^(array|string|int|float|bool|mixed|callable|iterable|object|null|self)$/i', $t)) continue;
                    $fq = resolveName($t, $uses, $ns);
                    if (isset($seen[$fq])) continue;
                    $add($pkgOf($fq), 'constructor', $consumer, $fq, $rel($file));
                    $seen[$fq] = true;
                }
            }
            foreach ($uses as $fq) {
                if (!isset($seen[$fq])) $add($pkgOf($fq), 'uses', $consumer, $fq, $rel($file));
            }
            continue;
        }
        if (str_ends_with($file, '.phtml')) continue;
        $xml = xmlText($file);
        if (preg_match('#/etc/(?:[a-z_]+/)?di\.xml$#', $file)) {
            preg_match_all('/<type\b([^>]*)>(.*?)<\/type>/s', $xml, $tm, PREG_SET_ORDER);
            foreach ($tm as $t) {
                $target = ltrim(attr($t[1], 'name'), '\\');
                if (preg_match_all('/<plugin\b([^>]*)\/?>/', $t[2], $plm)) {
                    foreach ($plm[1] as $pl) {
                        if (attr($pl, 'disabled') === 'true') continue;
                        $add($pkgOf($target), 'plugin', $consumer, $target . ' ← ' . ltrim(attr($pl, 'type'), '\\'), $rel($file));
                    }
                } else {
                    $add($pkgOf($target), 'di-arguments', $consumer, $target, $rel($file));
                }
            }
            preg_match_all('/<preference\b([^>]*)\/?>/', $xml, $prm);
            foreach ($prm[1] as $p) {
                $for = ltrim(attr($p, 'for'), '\\');
                $type = ltrim(attr($p, 'type'), '\\');
                $add($pkgOf($for), 'preference', $consumer, "$for → $type", $rel($file));
                if ($pkgOf($type) !== $pkgOf($for)) $add($pkgOf($type), 'di-arguments', $consumer, $type, $rel($file));
            }
            preg_match_all('/<virtualType\b([^>]*)>/', $xml, $vm);
            foreach ($vm[1] as $v) $add($pkgOf(ltrim(attr($v, 'type'), '\\')), 'di-arguments', $consumer, ltrim(attr($v, 'type'), '\\'), $rel($file));
            preg_match_all('/xsi:type="object"\s*>\s*([\\\\\w]+)\s*</', $xml, $om);
            foreach ($om[1] as $o) $add($pkgOf($o), 'di-arguments', $consumer, ltrim($o, '\\'), $rel($file));
        } elseif (preg_match('#/view/[a-z]+/layout/#', $file)) {
            preg_match_all('/\bclass="([\\\\\w]+)"/', $xml, $bm);
            foreach ($bm[1] as $c) $add($pkgOf($c), 'layout', $consumer, ltrim($c, '\\'), $rel($file));
