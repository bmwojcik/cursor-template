function resolveName(string $name, array $uses, string $ns): string
{
    if ($name[0] === '\\') return substr($name, 1);
    $first = explode('\\', $name)[0];
    return isset($uses[$first]) ? $uses[$first] . substr($name, strlen($first)) : ($ns !== '' ? "$ns\\$name" : $name);
}

